"""FRA Compliance Gate — standalone checker for Egyptian FRA Stage 1 KPIs.

Implements spec Section 7 (FRA Compliance Gate) and Section 7.2 (KPI Registry).

Public surface:
    FRA_KPI_REGISTRY          — dict of all 17 FRA KPIs with metadata
    MANDATORY_FRA_KPIS        — list of the 4 mandatory codes
    FRA_GATE_SCORE_CAP        — 60.0  (cap applied when gate fails)
    FRA_COVERAGE_THRESHOLD    — 0.50  (minimum ratio of KPIs that must be disclosed)

    check_fra_gate()                  — core gate logic (Spec §7.1)
    extract_fra_results_from_scores() — adapter: topic scores -> gate input
    get_fra_compliance_report()       — human-readable summary for report generator
"""
